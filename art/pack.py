"""python art/pack.py RENDER_DIR: build.py's frames -> graphics/entity/<sprite>[-shadow].png sheets, graphics/icons,
and prototypes/sprites.lua (each sheet's size, shift and frame count). Every frame of a sprite is cropped to the
same box; the shift is where that box sits against the image centre (the entity's position)."""
import sys
from pathlib import Path

from PIL import Image

PX = 64  # px a tile
MOD = Path(__file__).resolve().parent.parent
PER_ROW = 8


def bbox(images):
    box = None
    for im in images:
        b = im.getchannel("A").point(lambda a: 255 if a > 16 else 0).getbbox()
        if b:
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    return box


def sheet(images, out, shadow=False):
    if shadow:  # the shadow catcher's alpha -> black at full strength, as vanilla's shadow sheets are
        dark = []
        for im in images:
            a = im.getchannel("A").point(lambda v: min(255, int(v * 1.8)))
            k = Image.new("RGBA", im.size, (0, 0, 0, 0))
            k.putalpha(a)
            dark.append(k)
        images = dark
    for im in images:  # (the denoiser leaves faint alpha all over)
        im.putalpha(im.getchannel("A").point(lambda v: v if v > 16 else 0))
    l, t, r, b = bbox(images)
    l, t = max(0, l - 1), max(0, t - 1)
    r, b = min(images[0].width, r + 1), min(images[0].height, b + 1)
    w, h = r - l, b - t
    cols = min(PER_ROW, len(images))
    rows = -(-len(images) // cols)
    s = Image.new("RGBA", (w * cols, h * rows), (0, 0, 0, 0))
    for i, im in enumerate(images):
        s.paste(im.crop((l, t, r, b)), ((i % cols) * w, (i // cols) * h))
    out.parent.mkdir(parents=True, exist_ok=True)
    s.save(out, optimize=True)
    cx, cy = images[0].width / 2, images[0].height / 2
    shift = ((l + w / 2 - cx) / PX, (t + h / 2 - cy) / PX)
    return {"width": w, "height": h, "shift": shift, "frame_count": len(images), "line_length": cols}


def lua(v):
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k} = {lua(x)}" for k, x in v.items()) + "}"
    if isinstance(v, (tuple, list)):
        return "{" + ", ".join(lua(x) for x in v) + "}"
    if isinstance(v, float):
        return f"{v:.4f}".rstrip("0").rstrip(".")
    return str(v)


def pack_skin(src, skin):
    """one skin's frames -> graphics/entity/<skin>/<sprite>[-shadow|-glow].png, graphics/icons/<skin>/"""
    info = {}
    ent = MOD / "graphics" / "entity" / skin
    for d in sorted(p for p in src.iterdir() if p.is_dir() and p.name != "icons"):
        main_frames = [Image.open(p).convert("RGBA") for p in sorted(d.glob("[0-9][0-9].png"))]
        info[d.name] = sheet(main_frames, ent / f"{d.name}.png")
        for kind, shadow in (("shadow", True), ("glow", False)):
            extra = sorted(d.glob(f"*_{kind}.png"))
            if extra:
                info[f"{d.name}_{kind}"] = sheet([Image.open(p).convert("RGBA") for p in extra],
                                                 ent / f"{d.name}-{kind}.png", shadow=shadow)
    icons = MOD / "graphics" / "icons" / skin
    icons.mkdir(parents=True, exist_ok=True)
    for p in (src / "icons").glob("*.png"):
        Image.open(p).save(icons / p.name, optimize=True)
    return info


def main(src):
    src = Path(src)
    skins = {d.name: pack_skin(d, d.name) for d in sorted(src.iterdir()) if (d / "icons").is_dir()}
    lines = ["-- generated by art/pack.py from art/build.py's renders: don't edit", "return {"]
    for skin, info in skins.items():
        lines.append(f"  {skin} = {{")
        lines += [f"    {k} = {lua(v)}," for k, v in info.items()]
        lines.append("  },")
    lines.append("}")
    info = {f"{s}.{k}": v for s, i in skins.items() for k, v in i.items()}
    (MOD / "prototypes").mkdir(exist_ok=True)
    (MOD / "prototypes" / "sprites.lua").write_text("\n".join(lines) + "\n", newline="\n")
    for k, v in info.items():
        print(k, v)


if __name__ == "__main__":
    main(sys.argv[1])
